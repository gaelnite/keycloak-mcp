#!/usr/bin/env python3
"""Generate and check the Cedar policy bundle from the tool registry.

    python3 gen_cedar.py --write   # regenerate cedar/policies.cedar and entities.json
    python3 gen_cedar.py --check   # exit 1 if checked-in files drift from the registry

Keeping the registry as the single source of truth prevents the classic drift bug:
a tool exists in the MCP server but no policy (or entity) exists for it. The policy
text is intentionally explicit: one permit per tool, named after the tool's
``policy_id``, so decision logs and audits cite the exact tool policy.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from tool_registry import ADMIN, EXTENSIONS, READ, TOOLS, WRITE, ToolSpec

HERE = Path(__file__).resolve().parent
CEDAR = HERE.parent / "cedar"
POLICIES = CEDAR / "policies.cedar"
ENTITIES = CEDAR / "entities.json"

ACTION = {READ: "Read", WRITE: "Write", ADMIN: "Admin"}

_ALL_SCOPES = sorted({scope for tool in TOOLS for scope in tool.scopes})
_READ_SCOPES = sorted(
    {scope for tool in TOOLS if tool.tier == READ for scope in tool.scopes}
)

_HEADER = """\
// GENERATED by mcp/gen_cedar.py — do not edit by hand.
// Extension-aware Keycloak MCP policy bundle. Deny by default; every permit is
// scoped to exactly one tool, the caller's realm and (for extensions) an installed
// extension. Generic forbids below override every permit.

"""


def _permits() -> str:
    blocks: list[str] = []
    for tool in TOOLS:
        action = ACTION[tool.tier]
        conditions = [
            "context.toolKnown",
            f'resource.tier == "{tool.tier}"',
            "principal.scopes.contains(resource.requiredScope)",
            "principal in context.resource.realm",
            '(resource.extension == "core" || context.extensions.contains(resource.extension))',
        ]
        if tool.tier == WRITE:
            conditions.extend(
                [
                    "context.writesEnabled",
                    "context.approvalVerified",
                    "context.approvalTool == resource.name",
                ]
            )
        if tool.tier == ADMIN:
            conditions.append("principal.admin")
        when = "\n  && ".join(conditions)
        blocks.append(
            f'@id("{tool.policy_id}")\n'
            f"permit(\n"
            f"  principal,\n"
            f'  action == KeycloakMCP::Action::"{action}",\n'
            f'  resource == KeycloakMCP::Tool::"{tool.name}"\n'
            f")\n"
            f"when {{\n  {when}\n}};\n"
        )
    return "\n".join(blocks)


_FORBIDS = """\
@id("kc-deny-unknown-tool")
forbid(principal, action, resource)
when { !context.toolKnown };

@id("kc-deny-cross-realm")
forbid(principal, action, resource)
when { !(principal in context.resource.realm) };

@id("kc-deny-extension-missing")
forbid(principal, action, resource)
when {
  resource.extension != "core" &&
  !context.extensions.contains(resource.extension)
};

@id("kc-deny-writes-disabled")
forbid(principal, action, resource)
when {
  action == KeycloakMCP::Action::"Write" &&
  !context.writesEnabled
};

@id("kc-deny-unapproved-write")
forbid(principal, action, resource)
when {
  action == KeycloakMCP::Action::"Write" &&
  (!context.approvalVerified || context.approvalTool != resource.name)
};

@id("kc-deny-config-apply-without-admin")
forbid(principal, action, resource)
when {
  action == KeycloakMCP::Action::"Write" &&
  resource.extension == "config-cli" &&
  !principal.admin
};
"""


def render_policies() -> str:
    return _HEADER + _permits() + "\n" + _FORBIDS


def _entity(uid_type: str, uid_id: str, attrs: dict, parents: list[dict] | None = None) -> dict:
    return {
        "uid": {"type": f"KeycloakMCP::{uid_type}", "id": uid_id},
        "attrs": attrs,
        "parents": parents or [],
    }


def _realm_ref(realm: str) -> dict:
    return {"__entity": {"type": "KeycloakMCP::Realm", "id": realm}}


def render_entities() -> str:
    entities: list[dict] = [
        _entity("Realm", "lab", {}),
        _entity("Realm", "other", {}),
        _entity(
            "User",
            "alice",
            {"subject": "alice", "scopes": _ALL_SCOPES, "admin": True},
            [_realm_ref("lab")],
        ),
        _entity(
            "User",
            "bob",
            {"subject": "bob", "scopes": _READ_SCOPES, "admin": False},
            [_realm_ref("other")],
        ),
        _entity(
            "Client",
            "mcp-claude",
            {
                "clientId": "https://clients.example/claude.json",
                "scopes": _ALL_SCOPES,
                "admin": False,
            },
            [_realm_ref("lab")],
        ),
        _entity(
            "Client",
            "mcp-cursor",
            {
                "clientId": "https://clients.example/cursor.json",
                "scopes": _READ_SCOPES,
                "admin": False,
            },
            [_realm_ref("lab")],
        ),
        _entity(
            "Client",
            "mcp-admin",
            {
                "clientId": "https://clients.example/admin.json",
                "scopes": _ALL_SCOPES,
                "admin": True,
            },
            [_realm_ref("lab")],
        ),
    ]
    for tool in TOOLS:
        entities.append(
            _entity(
                "Tool",
                tool.name,
                {
                    "name": tool.name,
                    "requiredScope": tool.scopes[0],
                    "tier": tool.tier,
                    "extension": tool.extension,
                    "write": tool.write,
                },
            )
        )
    entities.extend(
        [
            _entity("Resource", "realm:lab", {"kind": "realm", "realm": _realm_ref("lab")}),
            _entity("Resource", "realm:other", {"kind": "realm", "realm": _realm_ref("other")}),
        ]
    )
    return json.dumps(entities, indent=2) + "\n"


def _write(path: Path, text: str) -> None:
    path.write_text(text)


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "--write" in args:
        _write(POLICIES, render_policies())
        _write(ENTITIES, render_entities())
        print(f"wrote {POLICIES.relative_to(HERE.parent)} and {ENTITIES.relative_to(HERE.parent)}")
        return 0
    if "--check" in args:
        drift = []
        if not POLICIES.is_file() or POLICIES.read_text() != render_policies():
            drift.append(str(POLICIES))
        if not ENTITIES.is_file() or ENTITIES.read_text() != render_entities():
            drift.append(str(ENTITIES))
        if drift:
            print("Cedar bundle is stale; run: python3 mcp/gen_cedar.py --write", file=sys.stderr)
            for path in drift:
                print(f"  drift: {path}", file=sys.stderr)
            return 1
        print("Cedar bundle matches the tool registry "
              f"({len(TOOLS)} tools, {len(set(EXTENSIONS))} extension names)")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
